export type IconName = keyof typeof ICONS;

/**
 * An icon by name. Inside shadcn components (buttons, menu items, badges) the component's own CSS sets the size.
 */
export const Icon = memo(function Icon({
  name,
  size = 18,
  className,
  label,
  ...rest
}: { name: IconName | string; size?: number; className?: string; label?: string } & Omit<SVGProps<SVGSVGElement>, 'name' | 'ref'>) {
  const Glyph = ICONS[name as IconName] ?? Sparkles;
  return (
    <Glyph
      className={cn('icon', className)}
      size={size}
      strokeWidth={1.8}
      aria-hidden={label ? undefined : true}
      role={label ? 'img' : undefined}
      aria-label={label}
      {...rest}
    />
  );
});
